import { writeFileSync } from 'node:fs';
import path from 'node:path';

import {
  COMPACT_TESSERACT_EDGE_KEYS,
  COMPACT_TESSERACT_FACE_KEY,
  createTesseractFrame,
  ETHEREUM_V_BASE,
} from '../src/lib/tesseract';

const projectRoot = path.resolve(__dirname, '..');
const publicIconPaths = [
  path.join(projectRoot, 'public', 'favicon.svg'),
  path.join(projectRoot, 'public', 'favicon-ethereum-tesseract.svg'),
];
const appIconPath = path.join(projectRoot, 'src', 'app', 'icon.svg');
const frame = createTesseractFrame();
const displayedFaces = frame.faces.filter(
  (face) => face.key === COMPACT_TESSERACT_FACE_KEY,
);
const displayedEdges = frame.edges.filter(
  (edge) => COMPACT_TESSERACT_EDGE_KEYS.has(edge.key),
);
const edgeColors = ['#a5f3fc', '#93c5fd', '#a5b4fc', '#d946ef'];
const number = (value: number) => value.toFixed(2).replace(/\.?0+$/, '');
const points = (vertices: ReadonlyArray<readonly [number, number]>) =>
  vertices.map((point) => point.join(',')).join(' ');
const baseLeftPoints = points([
  ETHEREUM_V_BASE.leftShoulder,
  ETHEREUM_V_BASE.notch,
  ETHEREUM_V_BASE.bottom,
]);
const baseRightPoints = points([
  ETHEREUM_V_BASE.rightShoulder,
  ETHEREUM_V_BASE.notch,
  ETHEREUM_V_BASE.bottom,
]);
const baseOutlinePath = [
  `M${ETHEREUM_V_BASE.leftShoulder.join(' ')}`,
  `L${ETHEREUM_V_BASE.notch.join(' ')}`,
  `L${ETHEREUM_V_BASE.rightShoulder.join(' ')}`,
  `L${ETHEREUM_V_BASE.bottom.join(' ')}`,
  'Z',
].join(' ');
const baseRidgePath = [
  `M${ETHEREUM_V_BASE.notch.join(' ')}`,
  `L${ETHEREUM_V_BASE.bottom.join(' ')}`,
].join(' ');
const faces = displayedFaces
  .map((face) => {
    const gradient = face.centroidX <= 128 ? 'face-light' : 'face-dark';
    const opacity = 0.32;
    const points = face.vertices
      .map((vertex) => {
        const point = frame.vertices[vertex];
        return `${number(point.x)},${number(point.y)}`;
      })
      .join(' ');

    return `    <polygon points="${points}" fill="url(#${gradient})" opacity="${number(opacity)}"/>`;
  })
  .join('\n');

const glowEdges = displayedEdges
  .map((edge) => {
    const from = frame.vertices[edge.from];
    const to = frame.vertices[edge.to];
    const width = 6.8 + edge.depth * 2.6;
    return `      <line x1="${number(from.x)}" y1="${number(from.y)}" x2="${number(to.x)}" y2="${number(to.y)}" stroke-width="${number(width)}"/>`;
  })
  .join('\n');

const crispEdges = displayedEdges
  .map((edge) => {
    const from = frame.vertices[edge.from];
    const to = frame.vertices[edge.to];
    const width = 4.8 + edge.depth * 1.8;
    const opacity = 0.86;
    return `      <line x1="${number(from.x)}" y1="${number(from.y)}" x2="${number(to.x)}" y2="${number(to.y)}" stroke="${edgeColors[edge.axis]}" stroke-width="${number(width)}" opacity="${number(opacity)}"/>`;
  })
  .join('\n');

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256" data-brand-silhouette="ethereum-tesseract-v">
  <!-- Generated by scripts/generate-tesseract-svg.ts from the real 4D projection. -->
  <defs>
    <linearGradient id="edge" x1="48" y1="24" x2="202" y2="232" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#a5f3fc"/>
      <stop offset=".5" stop-color="#818cf8"/>
      <stop offset="1" stop-color="#d946ef"/>
    </linearGradient>
    <radialGradient id="aura">
      <stop offset="0" stop-color="#818cf8" stop-opacity=".28"/>
      <stop offset=".62" stop-color="#7c3aed" stop-opacity=".14"/>
      <stop offset="1" stop-color="#c026d3" stop-opacity="0"/>
    </radialGradient>
    <linearGradient id="face-light" x1="58" y1="34" x2="170" y2="218" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#e0f2fe"/>
      <stop offset=".5" stop-color="#a5b4fc"/>
      <stop offset="1" stop-color="#6366f1"/>
    </linearGradient>
    <linearGradient id="face-dark" x1="92" y1="36" x2="202" y2="224" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#818cf8"/>
      <stop offset=".54" stop-color="#4f46e5"/>
      <stop offset="1" stop-color="#86198f"/>
    </linearGradient>
    <linearGradient id="base-left" x1="56" y1="180" x2="136" y2="240" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#cffafe"/>
      <stop offset=".46" stop-color="#a5b4fc"/>
      <stop offset="1" stop-color="#4f46e5"/>
    </linearGradient>
    <linearGradient id="base-right" x1="200" y1="180" x2="120" y2="240" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#a78bfa"/>
      <stop offset=".55" stop-color="#6d28d9"/>
      <stop offset="1" stop-color="#4c1d95"/>
    </linearGradient>
    <filter id="glow" x="-35%" y="-35%" width="170%" height="170%" color-interpolation-filters="sRGB">
      <feGaussianBlur stdDeviation="3.5"/>
    </filter>
  </defs>
  <ellipse cx="128" cy="118" rx="86" ry="106" fill="url(#aura)" opacity=".045" filter="url(#glow)"/>
  <g data-brand-part="ethereum-v-base" data-ethereum-v-base="stable">
    <g filter="url(#glow)" opacity=".14">
      <polygon points="${baseLeftPoints}" fill="url(#base-left)"/>
      <polygon points="${baseRightPoints}" fill="url(#base-right)"/>
    </g>
    <polygon points="${baseLeftPoints}" fill="url(#base-left)" opacity=".94"/>
    <polygon points="${baseRightPoints}" fill="url(#base-right)" opacity=".9"/>
    <path d="${baseOutlinePath}" fill="none" stroke="url(#edge)" stroke-linecap="round" stroke-linejoin="round" stroke-width="4.6" opacity=".9"/>
    <path d="${baseRidgePath}" fill="none" stroke="#c4b5fd" stroke-linecap="round" stroke-width="3.4" opacity=".68"/>
  </g>
  <g data-brand-part="upper-tesseract" data-upper-frame="none">
    <g>
${faces}
    </g>
    <g fill="none" stroke="url(#edge)" stroke-linecap="round" opacity=".24" filter="url(#glow)">
${glowEdges}
    </g>
    <g fill="none" stroke-linecap="round">
${crispEdges}
    </g>
  </g>
</svg>
`;

for (const publicIconPath of publicIconPaths) {
  writeFileSync(publicIconPath, svg);
}
writeFileSync(appIconPath, svg);
console.log(
  'Generated public favicon variants and src/app/icon.svg from the 4D projection',
);
